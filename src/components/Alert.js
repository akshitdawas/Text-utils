import React from 'react'

// ye wala  props.alert.type se type le rha hai......
// isme hum props.alert se msg aur type le rahe hain......
// agar props.alert null hoga toh alert show nhi hoga...... 
function Alert(props) { // ye function Alert component ko render karta hai......
  const capitalize = (word) => { // ye function msg ko capitali ze karta hai......
    const lower = word.toLowerCase(); // word ko lowercase me change karta hai......
    return lower.charAt(0).toUpperCase() + lower.slice(1); // word ko capitalize karke return karta hai......
  };

  return (
    <div style={{ height: '50px' }}> {/* yaha se height set kii hai*/}
      {props.alert && ( // ye syntax hai iska MATLAB hai ki agar props.alert null nahi hoga toh hi alert show hoga......
        <div className={`alert alert-${props.alert.type} alert-dismissible fade show`} role="alert"> {/* ye style hai alert ka jo alert ko red ya green color deta hai */}
          <strong>{capitalize(props.alert.type)}</strong>: {props.alert.msg} {/* yaha pe alert type aur msg ko show karega..... */}
        </div>
      )}
    </div>
  );
}

export default Alert